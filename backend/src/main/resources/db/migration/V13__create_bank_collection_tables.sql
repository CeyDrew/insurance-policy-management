-- Bank collection files (otomatik ödeme talimatı): request files sent to the bank and result files coming back.
-- File format: docs/bank-file-format.md

-- Bank auto-debit becomes a payment method of its own.
ALTER TABLE payment DROP CONSTRAINT ck_payment_method;
ALTER TABLE payment ADD CONSTRAINT ck_payment_method
    CHECK (payment_method IN ('CREDIT_CARD', 'BANK_TRANSFER', 'CASH', 'DIRECT_DEBIT'));

ALTER TABLE notification DROP CONSTRAINT ck_notification_type;
ALTER TABLE notification ADD CONSTRAINT ck_notification_type CHECK (notification_type IN (
    'RENEWAL_OFFER', 'INSTALLMENT_OVERDUE', 'POLICY_SUSPENDED', 'POLICY_EXPIRED',
    'CLAIM_STATUS_CHANGED', 'PAYMENT_RECEIVED', 'COLLECTION_REJECTED'));

CREATE SEQUENCE collection_file_seq START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE collection_file (
    id               NUMBER(19)         DEFAULT collection_file_seq.NEXTVAL NOT NULL,
    direction        VARCHAR2(10 CHAR)  NOT NULL,
    -- the request file a result file answers (file number in the header)
    request_file_id  NUMBER(19),
    file_name        VARCHAR2(200 CHAR) NOT NULL,
    storage_path     VARCHAR2(500 CHAR),
    file_hash        VARCHAR2(64 CHAR),
    file_date        DATE               NOT NULL,
    status           VARCHAR2(20 CHAR)  NOT NULL,
    record_count     NUMBER(10),
    total_amount     NUMBER(17, 2),
    collected_count  NUMBER(10)         DEFAULT 0 NOT NULL,
    collected_amount NUMBER(17, 2)      DEFAULT 0 NOT NULL,
    rejected_count   NUMBER(10)         DEFAULT 0 NOT NULL,
    error_count      NUMBER(10)         DEFAULT 0 NOT NULL,
    error_message    VARCHAR2(1000 CHAR),
    job_execution_id NUMBER(19),
    created_at       TIMESTAMP          DEFAULT SYSTIMESTAMP NOT NULL,
    created_by       VARCHAR2(50 CHAR)  DEFAULT 'system' NOT NULL,
    completed_at     TIMESTAMP,
    CONSTRAINT pk_collection_file PRIMARY KEY (id),
    CONSTRAINT fk_collection_file_request FOREIGN KEY (request_file_id) REFERENCES collection_file (id),
    CONSTRAINT ck_collection_file_direction CHECK (direction IN ('OUTBOUND', 'INBOUND')),
    CONSTRAINT ck_collection_file_status CHECK (status IN ('GENERATING', 'GENERATED', 'PROCESSING', 'COMPLETED', 'FAILED'))
);

-- A result file may be applied only once. A file that failed (e.g. trailer mismatch) does not block a retry,
-- hence a function-based unique index instead of a plain unique constraint.
CREATE UNIQUE INDEX ux_collection_file_hash ON collection_file (
    CASE WHEN direction = 'INBOUND' AND status <> 'FAILED' THEN file_hash END);

CREATE INDEX ix_collection_file_created ON collection_file (created_at);

-- Installments sent to the bank and the last answer for them.
ALTER TABLE installment ADD (
    collection_request_file_id NUMBER(19),
    collection_reject_code     VARCHAR2(2 CHAR),
    collection_rejected_at     TIMESTAMP,
    CONSTRAINT fk_installment_request_file FOREIGN KEY (collection_request_file_id) REFERENCES collection_file (id)
);
CREATE INDEX ix_installment_request_file ON installment (collection_request_file_id);

-- One row per detail line of an applied result file.
CREATE TABLE collection_result (
    id                 NUMBER(19)         GENERATED BY DEFAULT AS IDENTITY,
    collection_file_id NUMBER(19)         NOT NULL,
    line_no            NUMBER(10)         NOT NULL,
    installment_id     NUMBER(19),
    policy_number      VARCHAR2(30 CHAR),
    installment_no     NUMBER(2),
    amount             NUMBER(15, 2),
    result_code        VARCHAR2(2 CHAR),
    outcome            VARCHAR2(20 CHAR)  NOT NULL,
    payment_id         NUMBER(19),
    message            VARCHAR2(500 CHAR),
    created_at         TIMESTAMP          DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_collection_result PRIMARY KEY (id),
    CONSTRAINT fk_collection_result_file FOREIGN KEY (collection_file_id) REFERENCES collection_file (id),
    CONSTRAINT fk_collection_result_payment FOREIGN KEY (payment_id) REFERENCES payment (id),
    -- a line is applied at most once, even if a restarted job reads it again
    CONSTRAINT uk_collection_result_line UNIQUE (collection_file_id, line_no),
    CONSTRAINT ck_collection_result_outcome CHECK (outcome IN ('COLLECTED', 'REJECTED', 'ERROR'))
);
CREATE INDEX ix_collection_result_installment ON collection_result (installment_id);

-- Detail lines are handed to PL/SQL a chunk at a time as a collection of this type.
CREATE TYPE t_bank_result AS OBJECT (
    line_no        NUMBER(10),
    installment_id NUMBER(19),
    policy_number  VARCHAR2(30),
    installment_no NUMBER(2),
    amount         NUMBER(15, 2),
    result_code    VARCHAR2(2)
);
/

CREATE TYPE t_bank_result_tab AS TABLE OF t_bank_result;
